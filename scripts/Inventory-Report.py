"""Render scripts/DUNGEON-INVENTORY.md from scripts/generated/{inventory,discovery/*}.json.

    python scripts/Inventory-Report.py
"""

import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, "generated")

# Human conclusions the data alone cannot state. Everything else in the table is computed.
SPECIAL = {
    2998: "Outdoor terrain scenario (35 ground tiles with artefacts) plus 12 small cave WMOs; no single dungeon map identified and no boss "
          "coordinate source. Left unresolved on purpose.",
}
NOTES = {
    36: "Main mine WMO only. The ship area (Smite, Greenskin, Cookie, VanCleef) has no minimap tiles in this build; az_deadmines_d is unrelated.",
    189: "Four wing WMOs (yaw 0, ~1000 yd apart) shown as four pages: Graveyard, Library, Armory, Cathedral. All 340 spawns land in exactly one wing.",
    2999: "Ground tiles cropped to the walled ruined city (3x3 terrain grid with ruined town buildings). The Undercity WMO placed in this map is an underground piece, not the dungeon map.",
    33: "Single interior WMO with 7 Blizzard floors (97% of groups assigned directly).",
    47: "Single dungeon WMO (yaw 227). Ground tiles are outdoor terrain.",
    129: "Single dungeon WMO. Ground tiles are outdoor terrain.",
    43: "Forever's Wailing Caverns WMO is new (retail's differs); one floor.",
    48: "3 Blizzard floors; 37 listfile tile names do not exist at this build (stale, ignored).",
    70: "2 Blizzard floors.",
    90: "4 Blizzard floors; 6 connector groups appear on two floors.",
    3065: "WMO map (terrain tiles had a blank cell and grey backdrop). No boss coordinate source exists.",
}
GENERATED = {34, 43, 48, 70, 90, 47, 129, 33, 2999, 3065, 36, 189}


def load(name):
    with open(os.path.join(GEN, name), encoding="utf-8") as handle:
        return json.load(handle)


def main():
    inventory = load("inventory.json")
    prov = inventory["provenance"]
    lines = ["# Forever dungeon inventory", "",
             "Generated by `scripts/Inventory-Report.py` from `scripts/Discover-Dungeons.py` output. Do not edit.", "",
             "- Installed build: **%s** (build key `%s`)" % (prov["installedBuild"], prov["installedBuildKey"]),
             "- Provider (wago.tools) latest `wow_classic_beta`: %s, build config `%s` - match: **%s**" % (
                 prov["providerLatest"], prov["providerBuildConfig"], prov["buildKeyMatchesProvider"]),
             "- Version-scoped CASC rejects a bogus version (control): **%s**" % prov["bogusVersionRejected"], "",
             "| Dungeon | Map/InstanceID | Directory | Inst. type | WdtFileDataID | Native UiMap | Layout | Minimap source | Floors | Class | Mapping status |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in inventory["dungeons"]:
        d = load("discovery/%d.json" % row["mapID"])
        wmo = max(d["wmos"], key=lambda w: sum(len(g["tiles"]) for g in w["groups"])) if d["wmos"] else None
        ground = d.get("ground") or {}
        source = []
        if wmo:
            source.append("WMO %d (%d tiles)" % (wmo["rootFileDataID"], sum(len(g["tiles"]) for g in wmo["groups"])))
        if ground.get("tileCount"):
            source.append("ground %d tiles (%d non-blank)" % (ground["tileCount"], ground.get("contentTileCount", 0)))
        floors = wmo["floors"]["maxStackDepth"] if wmo else 1
        status = "ACCEPTED (hand-verified, build 70124 screenshot)" if d["mapID"] == 389 else (
            "candidate - generated, previewable offline/from anywhere" if d["mapID"] in GENERATED else "not generated")
        if d["mapID"] in SPECIAL:
            status = "unresolved"
        lines.append("| %s | %d | %s | %d | %d | %s | %s | %s | %s | %s | %s |" % (
            d["name"], d["mapID"], d["directory"], d["instanceType"], d["wdtFileDataID"],
            "none" if not d["nativeDungeonUiMaps"] else d["nativeDungeonUiMaps"], d["layout"],
            "; ".join(source) or "none", floors, d["classification"], status))
    lines += ["", "Classes: A native UiMap, B ground minimap, C WMO minimap, D mixed / multi-floor / multi-source, E none discovered.",
              "'Floors' is the deepest vertical stack of overlapping WMO groups (draw order = ascending min-Z); the viewer",
              "currently flattens it into one composite exactly as the accepted RFC view does.", "", "## Special handling and notes", ""]
    for map_id, text in sorted(SPECIAL.items()):
        lines.append("- **%d** %s" % (map_id, text))
    for map_id, text in sorted(NOTES.items()):
        lines.append("- **%d** %s" % (map_id, text))
    with open(os.path.join(HERE, "DUNGEON-INVENTORY.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote scripts/DUNGEON-INVENTORY.md")


if __name__ == "__main__":
    main()
