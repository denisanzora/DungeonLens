"""Evidence report: is floor separation needed/known for each dungeon? -> scripts/FLOOR-INVESTIGATION.md

For every registered map it combines (a) Blizzard's own floor assignment (Discover-Floors.py) with
(b) geometric evidence from the WMO groups themselves: how much of the painted area has two groups
stacked on top of each other (overlapping in XY but separated in Z). When Blizzard defines no floors
and stacking is negligible, flattening is justified; when stacking is large and Blizzard is silent the
map is flagged as UNVERIFIED rather than split by a guess.

    python scripts/Investigate-Floors.py
"""

import json
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from dl_common import build_floors, load, manifest_item, main_wmo  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
MAPS = [389, 3065, 2999, 43, 36, 33, 34, 48, 90, 47, 189, 129, 70]
Z_SEPARATION = 6.0  # yards between group z-ranges to count as vertically separate


def xy_overlap(a, b):
    w = min(a["maximum"][0], b["maximum"][0]) - max(a["minimum"][0], b["minimum"][0])
    h = min(a["maximum"][1], b["maximum"][1]) - max(a["minimum"][1], b["minimum"][1])
    return max(w, 0) * max(h, 0)


def stacking(groups):
    """Fraction of group-bbox area that is overlapped by a vertically separated group."""
    total = sum((g["maximum"][0] - g["minimum"][0]) * (g["maximum"][1] - g["minimum"][1]) for g in groups) or 1
    stacked = 0.0
    pairs = 0
    for i, a in enumerate(groups):
        for b in groups[i + 1:]:
            gap = max(a["minimum"][2] - b["maximum"][2], b["minimum"][2] - a["maximum"][2])
            if gap > Z_SEPARATION:
                area = xy_overlap(a, b)
                if area > 0:
                    stacked += area
                    pairs += 1
    return stacked / total, pairs


def main():
    lines = ["# Floor-separation investigation (build 1.60.1.70245)", "",
             "Generated by `scripts/Investigate-Floors.py`. 'Stacked area' = share of WMO-group bounding-box area that is overlapped by a",
             "group that is more than %.0f yd higher/lower. Blizzard floors come from retail UiMapAssignment (group IDs transferred exactly)." % Z_SEPARATION,
             "", "| Dungeon | Floors in addon | Floor source | Blizzard direct coverage | Stacked area | Stacked pairs | Verdict |",
             "| --- | --- | --- | --- | --- | --- | --- |"]
    summary = {}
    for map_id in MAPS:
        discovery = load("discovery/%d.json" % map_id)
        floors_info = load("floors/%d.json" % map_id)
        item = manifest_item(map_id)
        if item and item["source"] == "ground":
            lines.append("| %s | 1 (ground tiles) | n/a | n/a | n/a | n/a | single north-up ground map; no floors in data |" % discovery["name"])
            continue
        floors = build_floors(map_id, discovery, floors_info)
        wmo = floors[0]["wmo"]
        groups = [g for g in wmo["groups"] if g["tiles"]]
        fraction, pairs = stacking(groups)
        if item and item["source"] == "wmo-pages":
            verdict = "VERIFIED: %d wings = %d separate WMOs (exact; each boss lands in exactly one wing)" % (len(floors), len(floors))
            fraction, pairs = 0.0, 0
        elif len(floors) > 1:
            verdict = "VERIFIED: %d Blizzard floors, %.0f%% of groups assigned directly" % (len(floors), floors_info["directCoveragePercent"])
        elif fraction < 0.03:
            verdict = "single floor justified (stacking %.1f%% < 3%%)" % (100 * fraction)
        elif floors_info.get("status") == "retail-uimap-assignment" and len(floors_info["floors"]) == 1:
            verdict = "single floor per Blizzard (retail has one UiMap); stacking %.1f%% flattened" % (100 * fraction)
        else:
            verdict = "UNVERIFIED: %.1f%% stacked, Blizzard has no floor data - flattened, not split by guess" % (100 * fraction)
        summary[map_id] = {"floors": len(floors), "stackedFraction": round(fraction, 4), "verdict": verdict}
        lines.append("| %s | %d | %s | %s | %.1f%% | %d | %s |" % (
            discovery["name"], len(floors), floors[0]["source"],
            ("%s%%" % floors_info.get("directCoveragePercent")) if floors_info.get("directCoveragePercent") is not None else "n/a",
            100 * fraction, pairs, verdict))
    lines += ["", "Why not split by Z clustering alone: connector groups (stairs, ramps) legitimately span two levels (Gnomeregan has 6, Uldaman 1,",
              "BFD 1, SFK 5) and Blizzard lists them on both floors; a pure Z split cannot reproduce that. Floors are therefore taken from",
              "Blizzard's assignment where it exists and left single (flagged) where it does not."]
    with open(os.path.join(HERE, "FLOOR-INVESTIGATION.md"), "w", encoding="utf-8", newline="\n") as handle:
        handle.write("\n".join(lines) + "\n")
    with open(os.path.join(HERE, "generated", "floor-investigation.json"), "w", encoding="utf-8", newline="\n") as handle:
        json.dump(summary, handle, indent=1, sort_keys=True)
        handle.write("\n")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
