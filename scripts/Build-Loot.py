"""Build the runtime loot dataset and its provenance report from the resolved loot JSON.

Inputs : generated/loot/<map>.json (Resolve-Loot.py), generated/bosses/<map>.json (boss identities used by BossData.lua)
Outputs: LootData.lua                (ns.BossLoot, keyed by the same boss/encounter ID as BossData.lua)
         scripts/LOOT-PROVENANCE.md  (every item: dungeon, boss, IDs, name, source, confidence, Forever-specific?)
         generated/loot/all.json     (consumed by Build-Previews.py)

Policy (see LOOT-PROVENANCE.md): only items whose numeric ID is verified in Forever's own Item table AND whose boss association
comes from a Forever-specific listing are shipped. Drop percentages are NOT shipped: the sources either state Classic-derived
values ("no drops seen in Forever yet") or do not say. Bosses with no verified items get no entry (UI: "No verified loot yet").

    python scripts/Build-Loot.py [--check]
"""

import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
GEN = os.path.join(HERE, "generated")
SOURCE = "wowtbc.gg Warcraft Forever loot tables (Forever-specific; flags Forever-new items)"
# Boss->item names independently confirmed by a second Forever listing (wowf.io) and item IDs by two ID-bearing databases
# (foreverdb.net, wowforever.wclbox.com) when checked on 2026-10-07. Only these were cross-checked item by item.
CORROBORATED = {389: {"Taragaman the Hungerer", "Jergosh the Invoker"}}
MAPS = [389, 3065, 2999, 43, 36, 33, 34, 48, 90, 47, 189, 129, 70, 2998]


def load(path):
    with open(os.path.join(GEN, path), encoding="utf-8") as handle:
        return json.load(handle)


def build():
    names = {}
    data, report = {}, []
    for map_id in MAPS:
        bosses = load("bosses/%d.json" % map_id)
        loot = load("loot/%d.json" % map_id)
        dungeon = bosses["name"]
        by_id = {b["id"]: b for b in bosses["bosses"]}
        merged = {}
        for entry in loot["bosses"]:
            slot = merged.setdefault(entry["encounterID"], {"items": [], "sourceItems": 0, "sources": []})
            slot["sourceItems"] += entry["sourceItemCount"]
            slot["sources"].append(entry["sourceBoss"])
            for item in entry["items"]:
                if all(i["itemID"] != item["itemID"] for i in slot["items"]):
                    slot["items"].append(item)
        unresolved = {}
        for u in loot["unresolvedItems"]:
            unresolved.setdefault(u["boss"], []).append(u)
        for boss in bosses["bosses"]:
            record = merged.get(boss["id"])
            confidence = "forever-corroborated" if boss["name"] in CORROBORATED.get(map_id, set()) else "forever-listed"
            row = {"map": map_id, "dungeon": dungeon, "boss": boss["name"], "encounterID": boss["id"], "markerStatus": boss["status"],
                   "items": [], "unverifiedItems": [], "sourceBoss": record["sources"] if record else []}
            if record:
                for item in record["items"]:
                    row["items"].append({"itemID": item["itemID"], "name": item["name"], "slot": item["slot"], "foreverNew": item["foreverNew"],
                                         "source": SOURCE, "confidence": confidence, "foreverSpecific": True,
                                         "idSource": item["idSource"], "sourcePercent": item["sourcePercent"]})
                    names[item["itemID"]] = item["name"]
            for u in unresolved.get(boss["name"], []):
                row["unverifiedItems"].append({"name": u["name"], "reason": u["reason"]})
            # a boss listed under a source alias keeps its unresolved items too
            for alias in (record["sources"] if record else []):
                for u in unresolved.get(alias, []):
                    if u not in row["unverifiedItems"] and all(x["name"] != u["name"] for x in row["unverifiedItems"]):
                        row["unverifiedItems"].append({"name": u["name"], "reason": u["reason"]})
            row["complete"] = bool(row["items"]) and not row["unverifiedItems"]
            report.append(row)
    return report, names


def lua(report):
    lines = ["-- GENERATED by scripts/Build-Loot.py from scripts/generated/loot/*.json. DO NOT EDIT.",
             "-- Boss loot keyed by the same boss/encounter ID as BossData.lua. Every itemID is verified in Forever's Item table and",
             "-- every boss->item association comes from a Forever-specific listing (scripts/LOOT-PROVENANCE.md). No drop rates are",
             "-- shipped (sources are Classic-derived or silent). `partial` = the Forever listing names more drops whose IDs are unverified.",
             "local _, ns = ...", "ns.BossLoot = {"]
    for row in report:
        if not row["items"]:
            continue
        lines.append("    [%d] = { -- %s: %s" % (row["encounterID"], row["dungeon"], row["boss"]))
        lines.append("        partial = %s," % ("true" if row["unverifiedItems"] else "false"))
        lines.append("        items = {")
        for item in row["items"]:
            lines.append("            { itemID = %d, name = %s, confidence = %s }," % (item["itemID"], json.dumps(item["name"]), json.dumps(item["confidence"])))
        lines += ["        },", "    },"]
    lines.append("}")
    return "\n".join(lines) + "\n"


def markdown(report):
    lines = ["# Boss loot provenance (build 1.60.1.70245)", "",
             "Generated by `scripts/Build-Loot.py`. **Source of boss->item associations:** %s. **Item IDs** are verified against Forever's own "
             "client `Item` table (names from Forever `ItemSparse`, falling back to Classic Era `ItemSparse` when Forever's export omits the "
             "name). Forever-*new* items have no name in the client tables, so their IDs come from foreverdb.net item links "
             "(`generated/loot/foreverdb-ids.json`) and are shipped only when that ID exists in Forever's `Item` table and its equip slot fits "
             "the listing. Quality is *not* used to match Classic-named items because Forever revised dungeon item quality (e.g. Cursed Felblade is "
             "green in Classic, blue in Forever); in-game tooltips are the authority for stats." % SOURCE, "",
             "**Not shipped, on purpose:** (1) drop percentages: the Forever listing's numbers are not stated as Forever-measured and "
             "`foreverdb.net` says its values are Classic data with \"no drops seen in Forever yet\"; (2) Forever-*new* items whose numeric "
             "ID could not be verified (not linked by foreverdb.net, or the linked ID is not in Forever's Item table / does not fit the slot); (3) name collisions between a "
             "Classic ID and a Forever-reissued ID (e.g. Robe of Doan 7711 vs 217297) where the evidence does not decide.", "",
             "Confidence: **forever-corroborated** = boss->item names agree across two Forever listings and the IDs across two ID-bearing "
             "databases; **forever-listed** = one Forever listing, ID verified in client tables (Forever-new items: foreverdb.net ID checked against the Item table). `Forever-specific` = the listing is a "
             "Forever database (true for all shipped rows); it does not claim the drop was observed in Forever.", "",
             "| Dungeon | Boss | Encounter ID | Item ID | Item | Slot | Forever-new | Source | Confidence | Forever-specific |",
             "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]
    for row in report:
        for item in row["items"]:
            lines.append("| %s | %s | %d | %d | %s | %s | %s | %s | %s | yes |" % (
                row["dungeon"], row["boss"], row["encounterID"], item["itemID"], item["name"], item["slot"],
                "yes" if item["foreverNew"] else "no", "wowtbc.gg/warcraftforever", item["confidence"]))
    lines += ["", "## Bosses without complete verified loot", "",
              "| Dungeon | Boss | Encounter ID | Shipped items | Listed but unverified (not shipped) | Why |", "| --- | --- | --- | --- | --- | --- |"]
    for row in report:
        if row["complete"]:
            continue
        reasons = sorted({u["reason"].split(":")[0] for u in row["unverifiedItems"]}) or ["no entry for this boss in the Forever listing"]
        lines.append("| %s | %s | %d | %d | %s | %s |" % (row["dungeon"], row["boss"], row["encounterID"], len(row["items"]),
                                                         ", ".join(u["name"] for u in row["unverifiedItems"]) or "-", "; ".join(reasons)))
    complete = {}
    for row in report:
        complete.setdefault(row["dungeon"], []).append(row["complete"])
    lines += ["", "## Dungeon completeness", "", "| Dungeon | Bosses with complete verified loot |", "| --- | --- |"]
    for dungeon, flags in complete.items():
        lines.append("| %s | %d of %d |" % (dungeon, sum(flags), len(flags)))
    return "\n".join(lines) + "\n"


def main():
    report, names = build()
    outputs = {os.path.join(ROOT, "LootData.lua"): lua(report), os.path.join(HERE, "LOOT-PROVENANCE.md"): markdown(report),
               os.path.join(GEN, "loot", "all.json"): json.dumps(report, indent=1, sort_keys=True) + "\n"}
    if "--check" in sys.argv:
        for path, text in outputs.items():
            assert open(path, encoding="utf-8").read() == text, os.path.basename(path) + " is stale"
        print("loot outputs are current")
        return
    for path, text in outputs.items():
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    bosses = sum(1 for r in report if r["items"])
    unique = {i["itemID"] for r in report for i in r["items"]}
    print("bosses with loot: %d of %d; unique items: %d; item rows: %d" % (bosses, len(report), len(unique), sum(len(r["items"]) for r in report)))
    for dungeon in dict.fromkeys(r["dungeon"] for r in report):
        rows = [r for r in report if r["dungeon"] == dungeon]
        print("  %-26s with loot %d/%d, complete %d" % (dungeon, sum(1 for r in rows if r["items"]), len(rows), sum(r["complete"] for r in rows)))


if __name__ == "__main__":
    main()
